import p from 'puppeteer-core';
const url=process.argv[2]||'http://localhost:8779/legs-v1/index.html';
const b=await p.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const pg=await b.newPage();pg.on('pageerror',e=>console.log('E',e.message));
pg.on('console',m=>{if(m.type()==='error'||m.type()==='warning')console.log('C',m.text())});
await pg.setViewport({width:390,height:844,deviceScaleFactor:2});
await pg.goto(url,{waitUntil:'networkidle0',timeout:120000});
await pg.waitForFunction('window.ready',{timeout:90000});
const sh=async(f)=>{await new Promise(r=>setTimeout(r,1800));await pg.screenshot({path:'shots/'+f});console.log('shot',f)};
await pg.evaluate(()=>{setCovers(false);setCom(true);setAuto(true);setDir(1,0.05,0.12);snapFit()});
await sh('01_full_front.png');
await pg.evaluate(()=>{setDir(0.03,0.08,1);snapFit()});
await sh('02_full_side_com.png');
await pg.evaluate(()=>{setDir(0.7,0.35,0.6);snapFit()});
await sh('03_full_iso.png');
await pg.evaluate(()=>{setWalk(true,0);setDir(0.05,0.1,1);snapFit()});
await sh('04_walk_side_phase0.png');
await pg.evaluate(()=>{setWalk(true,Math.PI/2)});
await sh('05_walk_side_phaseHalfPI.png');
await pg.evaluate(()=>{setWalk(false);setJ({pitch_L:30,knee_L:60,ap_L:-10,pitch_R:-10,ap_R:20,ar_R:10});setDir(0.6,0.45,0.75);snapFit()});
await sh('06_legs_posed.png');
await pg.evaluate(()=>{setJ({pitch_L:0,knee_L:0,ap_L:0,pitch_R:0,ap_R:0,ar_R:0});M.arm.forEach(m=>m.visible=false);setDir(0.2,-0.9,0.5);snapFit()});
await sh('07_soles_below.png');
await b.close();
